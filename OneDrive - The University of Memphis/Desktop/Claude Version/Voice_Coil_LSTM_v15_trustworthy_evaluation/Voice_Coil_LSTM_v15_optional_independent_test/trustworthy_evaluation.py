def configure(arguments: argparse.Namespace) -> dict:
    if arguments.full and arguments.smoke_test:
        raise ValueError("Choose either --full or --smoke-test, not both.")
    if arguments.seeds is not None:
        seeds = list(dict.fromkeys(arguments.seeds))
    elif arguments.smoke_test:
        seeds = [123, 456]
    elif arguments.full:
        seeds = FINAL_SEEDS
    else:
        seeds = DEFAULT_SEEDS
    if not seeds:
        raise ValueError("At least one seed is required.")
    if (
        arguments.mode in ("baseline", "repeatability", "all")
        and not arguments.smoke_test
        and len(seeds) < 5
    ):
        raise ValueError(
            "A reportable repeatability/baseline study requires at least 5 seeds."
        )
    if arguments.full and len(seeds) < 10:
        raise ValueError("--full requires at least 10 seeds.")
    epochs = arguments.epochs or (1 if arguments.smoke_test else 20)
    samples = arguments.samples_per_epoch or (512 if arguments.smoke_test else 20000)
    if arguments.ablation_max_removals < 0:
        raise ValueError("--ablation-max-removals cannot be negative.")
    max_removals = min(
        arguments.ablation_max_removals,
        1 if arguments.smoke_test else len(ONE_STEP_FEATURE_NAMES) - 1,
    )
    if epochs < 1 or samples < 1 or arguments.patience < 1:
        raise ValueError("Epochs, samples per epoch, and patience must be positive.")
    if arguments.validation_fit_drop < 0 or arguments.validation_rmse_increase < 0:
        raise ValueError("Ablation tolerances cannot be negative.")
    label = "SMOKE_NOT_REPORTABLE" if arguments.smoke_test else "REPORTABLE"
    root = HERE / (
        "TrustworthyEvaluation_SMOKE_NOT_REPORTABLE"
        if arguments.smoke_test else "TrustworthyEvaluation"
    )
    return {
        "seeds": seeds,
        "epochs": epochs,
        "samples": samples,
        "patience": arguments.patience,
        "max_removals": max_removals,
        "candidate_limit": 3 if arguments.smoke_test else None,
        "label": label,
        "root": root,
    }


def seed_everything(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    torch.use_deterministic_algorithms(True, warn_only=True)
    if hasattr(torch.backends, "cudnn"):
        torch.backends.cudnn.benchmark = False
        torch.backends.cudnn.deterministic = True


def strict_role_pairs(records: list[dict], role: str) -> np.ndarray:
    """Build windows whose entire measured-feedback history stays in one role."""
    pairs = []
    for record_index, record in enumerate(records):
        if record["is_pure_test"]:
            continue
        for _, start, stop, block_role in record["blocks"]:
            if block_role != role:
                continue
            first_target = start + HISTORY_SAMPLES - 1
            pairs.extend((record_index, target) for target in range(first_target, stop))
    result = np.asarray(pairs, dtype=np.int64)
    if result.size == 0:
        raise RuntimeError(f"No strict {role} one-step windows were produced.")
    return result.reshape(-1, 2)


def pure_pairs(data: dict, name: str) -> np.ndarray:
    record_index = data["index_of"][name]
    record = data["records"][record_index]
    targets = np.arange(record["pad"], record["samples"], dtype=np.int64)
    return np.column_stack([
        np.full(len(targets), record_index, dtype=np.int64), targets
    ])


def ensure_one_step_arrays(records, include_pure=False) -> None:
    """Construct causal arrays only for the roles currently needed."""
    for record in records:
        if record["is_pure_test"] and not include_pure:
            continue
        if "one_step" not in record:
            record["one_step"] = _make_causal_arrays(record)


class SelectedFeatureDataset(Dataset):
    def __init__(self, records, pairs, indices, statistics):
        self.records = records
        self.pairs = np.asarray(pairs, dtype=np.int64)
        self.indices = np.asarray(indices, dtype=np.int64)
        self.feature_mean, self.feature_std, self.target_mean, self.target_std = statistics

    def __len__(self):
        return len(self.pairs)

    def __getitem__(self, item):
        record_index, target = self.pairs[item]
        record = self.records[record_index]
        window = record["one_step"]["features"][
            target - HISTORY_SAMPLES + 1: target + 1, self.indices
        ]
        window = ((window - self.feature_mean) / self.feature_std).astype(np.float32)
        residual = record["one_step"]["displacement_residual"][target]
        target_value = np.float32((residual - self.target_mean) / self.target_std)
        return torch.from_numpy(np.ascontiguousarray(window)), torch.tensor(target_value)


def training_statistics(records, pairs, indices):
    features = np.stack([
        records[r]["one_step"]["features"][t, indices] for r, t in pairs
    ]).astype(np.float64)
    residuals = np.asarray([
        records[r]["one_step"]["displacement_residual"][t] for r, t in pairs
    ], dtype=np.float64)
    feature_mean = features.mean(axis=0)
    feature_std = features.std(axis=0)
    feature_std[feature_std < 1e-8] = 1.0
    target_mean = float(residuals.mean())
    target_std = max(float(residuals.std()), 1e-8)
    return feature_mean, feature_std, target_mean, target_std


def predict_residual(bundle, record, targets, device):
    indices = bundle["indices"]
    feature_mean, feature_std, target_mean, target_std = bundle["statistics"]
    windows = np.asarray([
        (
            record["one_step"]["features"][
                target - HISTORY_SAMPLES + 1: target + 1, indices
            ] - feature_mean
        ) / feature_std
        for target in targets
    ], dtype=np.float32)
    parts = []
    bundle["model"].eval()
    with torch.no_grad():
        for start in range(0, len(windows), 512):
            batch = torch.from_numpy(windows[start:start + 512]).to(device)
            parts.append(bundle["model"](batch).cpu().numpy())
    return np.concatenate(parts) * target_std + target_mean


def validation_trust(bundle, records, validation_pairs, device) -> float:
    actual_parts = []
    predicted_parts = []
    for record_index in sorted(set(validation_pairs[:, 0].tolist())):
        subset = validation_pairs[validation_pairs[:, 0] == record_index]
        record = records[record_index]
        targets = subset[:, 1]
        predicted_parts.append(predict_residual(bundle, record, targets, device))
        actual_parts.append(record["one_step"]["displacement_residual"][targets])
    actual = np.concatenate(actual_parts).astype(np.float64)
    predicted = np.concatenate(predicted_parts).astype(np.float64)
    denominator = float(np.dot(predicted, predicted))
    if denominator <= 1e-20:
        return 0.0
    return float(np.clip(np.dot(actual, predicted) / denominator, 0.0, 1.0))


def train_predictor(
    records, training_pairs, validation_pairs, feature_indices, seed, device,
    epochs, samples_per_epoch, patience, verbose=True,
):
    seed_everything(seed)
    indices = tuple(int(value) for value in feature_indices)
    statistics = training_statistics(records, training_pairs, indices)
    training_set = SelectedFeatureDataset(records, training_pairs, indices, statistics)
    validation_set = SelectedFeatureDataset(records, validation_pairs, indices, statistics)
    counts = np.bincount(training_pairs[:, 0], minlength=len(records))
    weights = np.asarray([1.0 / counts[r] for r, _ in training_pairs], dtype=np.float64)
    generator = torch.Generator().manual_seed(seed)
    sampler = WeightedRandomSampler(
        weights, samples_per_epoch, replacement=True, generator=generator
    )
    training_loader = DataLoader(training_set, batch_size=BATCH_SIZE, sampler=sampler, num_workers=0)
    validation_loader = DataLoader(validation_set, batch_size=512, shuffle=False, num_workers=0)
    model = OneStepDisplacementLSTM(input_features=len(indices)).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=1e-3, weight_decay=1e-6)
    loss_function = nn.MSELoss()
    best_loss = np.inf
    best_state = deepcopy(model.state_dict())
    stale = 0
    history = []
    for epoch in range(1, epochs + 1):
        model.train()
        training_losses = []
        for inputs, targets in training_loader:
            inputs, targets = inputs.to(device), targets.to(device)
            optimizer.zero_grad(set_to_none=True)
            loss = loss_function(model(inputs), targets)
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            training_losses.append(float(loss.item()))
        model.eval()
        validation_losses = []
        with torch.no_grad():
            for inputs, targets in validation_loader:
                inputs, targets = inputs.to(device), targets.to(device)
                validation_losses.append(float(loss_function(model(inputs), targets).item()))
        train_loss = float(np.mean(training_losses))
        validation_loss = float(np.mean(validation_losses))
        history.append((epoch, train_loss, validation_loss))
        if verbose:
            print(
                f"  seed {seed}, {len(indices):02d} features, epoch {epoch:02d}: "
                f"train={train_loss:.6f}, validation={validation_loss:.6f}", flush=True,
            )
        if validation_loss < best_loss - 1e-5:
            best_loss = validation_loss
            best_state = deepcopy(model.state_dict())
            stale = 0
        else:
            stale += 1
            if stale >= patience:
                break
    model.load_state_dict(best_state)
    bundle = {
        "model": model,
        "indices": indices,
        "statistics": statistics,
        "seed": seed,
        "best_validation_loss": float(best_loss),
        "history": history,
    }
    bundle["trust"] = validation_trust(bundle, records, validation_pairs, device)
    return bundle


def predictions_for_record(bundle, record, targets, startup_gain, device):
    measured = record["outputs"][targets].astype(np.float64)
    persistence = record["outputs"][targets - 1].astype(np.float64)
    causal_force = _force_prediction(record, targets, startup_gain).astype(np.float64)
    causal_displacement = record["one_step"]["displacement_baseline"][targets].astype(np.float64)
    residual = predict_residual(bundle, record, targets, device).astype(np.float64)
    causal = np.column_stack([causal_displacement, causal_force])
    hybrid = np.column_stack([
        causal_displacement + bundle["trust"] * residual,
        causal_force,
    ])
    return measured, {
        "persistence": persistence,
        "causal_baseline": causal,
        "hybrid_lstm": hybrid,
    }


def lag_one(values) -> float:
    values = np.asarray(values, dtype=np.float64)
    if len(values) < 3 or np.std(values[:-1]) <= 1e-15 or np.std(values[1:]) <= 1e-15:
        return np.nan
    return float(np.corrcoef(values[:-1], values[1:])[0, 1])


def metric_row(seed, method, evaluation, output, unit, time, measured, predicted):
    values = calculate_metrics(
        measured, predicted, negligible_range=NEGLIGIBLE_SIGNAL_RANGE[output]
    )
    error = np.asarray(measured, dtype=np.float64) - np.asarray(predicted, dtype=np.float64)
    error_std = float(np.std(error, ddof=1)) if len(error) > 1 else 0.0
    final_count = max(1, min(len(error), max(10, int(np.ceil(0.10 * len(error))))))
    final_drift = float(np.mean(error[-final_count:]))
    duration = float(time[-1] - time[0]) if len(time) > 1 else 0.0
    slope = float(np.polyfit(time, error, 1)[0]) if duration > 0 else np.nan
    autocorrelation = lag_one(error)
    warnings = []
    if np.isfinite(autocorrelation) and abs(autocorrelation) > 0.20:
        warnings.append("lag-1 correlation")
    if np.isfinite(slope) and abs(slope) * duration > 0.25 * max(error_std, 1e-12):
        warnings.append("trend")
    if abs(final_drift) > 0.50 * max(values["RMSE"], 1e-12):
        warnings.append("final drift")
    return {
        "Seed": seed,
        "Method": method,
        "Evaluation": evaluation,
        "Output": output,
        "Unit": unit,
        "Samples": len(error),
        **values,
        "ErrorMean": float(np.mean(error)),
        "ErrorStd": error_std,
        "ResidualLag1": autocorrelation,
        "ResidualTrendPerSecond": slope,
        "FinalDrift": final_drift,
        "DiagnosticWarning": "; ".join(warnings) if warnings else "none",
    }


def evaluate_pure_tests(bundle, data, startup_gain, device):
    # Feature/hyperparameter choices have already been frozen by every caller.
    ensure_one_step_arrays(data["records"], include_pure=True)
    rows = []
    pooled = {method: {"measured": [], "predicted": []} for method in METHODS}
    worst = None
    for name in data["pure_test_names"]:
        pairs = pure_pairs(data, name)
        record = data["records"][int(pairs[0, 0])]
        targets = pairs[:, 1]
        time = record["time"][targets].astype(np.float64)
        measured, predictions = predictions_for_record(bundle, record, targets, startup_gain, device)
        for method, predicted in predictions.items():
            pooled[method]["measured"].append(measured)
            pooled[method]["predicted"].append(predicted)
            for column, output, unit in ((0, "Displacement", "mm"), (1, "Lorentz force", "N")):
                row = metric_row(
                    bundle["seed"], method, name, output, unit, time,
                    measured[:, column], predicted[:, column],
                )
                row["Test_origin"] = record["source_workbook"]
                rows.append(row)
                if method == "hybrid_lstm" and output == "Displacement":
                    score = row["Fit_percent"]
                    score = score if np.isfinite(score) else -np.inf
                    if worst is None or score < worst["fit"]:
                        worst = {
                            "fit": score, "seed": bundle["seed"], "name": name,
                            "time": time.copy(), "measured": measured.copy(),
                            "predicted": predicted.copy(),
                        }
    for method in METHODS:
        measured = np.concatenate(pooled[method]["measured"])
        predicted = np.concatenate(pooled[method]["predicted"])
        time = np.arange(len(measured), dtype=np.float64) * TARGET_TIME_STEP
        for column, output, unit in ((0, "Displacement", "mm"), (1, "Lorentz force", "N")):
            row = metric_row(
                bundle["seed"], method, "ALL_PURE_TESTS_POOLED", output, unit,
                time, measured[:, column], predicted[:, column],
            )
            row["Test_origin"] = "pooled"
            rows.append(row)
    return pd.DataFrame(rows), worst


def confidence_summary(values) -> dict:
    values = pd.to_numeric(pd.Series(values), errors="coerce").dropna().to_numpy(float)
    n = len(values)
    if n == 0:
        return {"mean": np.nan, "std": np.nan, "min": np.nan, "max": np.nan,
                "ci95_low": np.nan, "ci95_high": np.nan, "n": 0}
    mean = float(np.mean(values))
    standard_deviation = float(np.std(values, ddof=1)) if n > 1 else 0.0
    if n > 1:
        half_width = float(scipy_stats.t.ppf(0.975, n - 1) * standard_deviation / np.sqrt(n))
        low, high = mean - half_width, mean + half_width
    else:
        low = high = np.nan
    return {
        "mean": mean, "std": standard_deviation, "min": float(np.min(values)),
        "max": float(np.max(values)), "ci95_low": low, "ci95_high": high, "n": n,
    }


def summarise_metrics(raw: pd.DataFrame) -> pd.DataFrame:
    rows = []
    keys = ["Method", "Evaluation", "Output", "Unit"]
    for key, group in raw.groupby(keys, sort=False):
        row = dict(zip(keys, key))
        row["Seeds"] = int(group["Seed"].nunique())
        for metric in METRICS:
            summary = confidence_summary(group[metric])
            for statistic, value in summary.items():
                row[f"{metric}_{statistic}"] = value
            if np.isfinite(summary["mean"]):
                row[f"{metric}_mean_plus_minus_SD"] = (
                    f"{summary['mean']:.8g} +/- {summary['std']:.3g}"
                )
            else:
                row[f"{metric}_mean_plus_minus_SD"] = "N/A (flat reference)"
        rows.append(row)
    return pd.DataFrame(rows)


def paired_improvements(raw: pd.DataFrame) -> pd.DataFrame:
    hybrid = raw[raw["Method"] == "hybrid_lstm"]
    rows = []
    for baseline in ("persistence", "causal_baseline"):
        other = raw[raw["Method"] == baseline]
        keys = ["Seed", "Evaluation", "Output"]
        joined = hybrid.merge(other, on=keys, suffixes=("_hybrid", "_baseline"))
        for (evaluation, output), group in joined.groupby(["Evaluation", "Output"], sort=False):
            for metric in ("RMSE", "MAE", "NRMSE_percent", "R2", "Fit_percent"):
                if metric in ("RMSE", "MAE", "NRMSE_percent"):
                    improvement = group[f"{metric}_baseline"] - group[f"{metric}_hybrid"]
                    definition = "baseline minus hybrid; positive favors hybrid"
                else:
                    improvement = group[f"{metric}_hybrid"] - group[f"{metric}_baseline"]
                    definition = "hybrid minus baseline; positive favors hybrid"
                summary = confidence_summary(improvement)
                clear = bool(summary["n"] >= 2 and summary["ci95_low"] > 0)
                worse = bool(summary["n"] >= 2 and summary["ci95_high"] < 0)
                rows.append({
                    "Baseline": baseline, "Evaluation": evaluation, "Output": output,
                    "Metric": metric, "Difference_definition": definition,
                    "Mean_improvement": summary["mean"], "SD": summary["std"],
                    "Minimum": summary["min"], "Maximum": summary["max"],
                    "CI95_low": summary["ci95_low"], "CI95_high": summary["ci95_high"],
                    "Paired_runs": summary["n"],
                    "Clear_hybrid_improvement": clear,
                    "Clear_hybrid_worse": worse,
                    "Interpretation": (
                        "clear improvement" if clear else "clear worsening" if worse
                        else "uncertain/no clear difference"
                    ),
                })
    return pd.DataFrame(rows)


def model_ranking(raw: pd.DataFrame, paired: pd.DataFrame) -> pd.DataFrame:
    pooled = raw[raw["Evaluation"] == "ALL_PURE_TESTS_POOLED"]
    rows = []
    for (output, method), group in pooled.groupby(["Output", "Method"], sort=False):
        rmse = confidence_summary(group["RMSE"])
        fit = confidence_summary(group["Fit_percent"])
        r2 = confidence_summary(group["R2"])
        individual = raw[(raw["Method"] == method) & (raw["Output"] == output)
                         & (raw["Evaluation"] != "ALL_PURE_TESTS_POOLED")]
        test_means = individual.groupby("Evaluation")["RMSE"].mean()
        worst_name = test_means.idxmax() if len(test_means) else "N/A"
        rows.append({
            "Output": output, "Method": method,
            "Mean_RMSE": rmse["mean"], "RMSE_SD_across_seeds": rmse["std"],
            "RMSE_CI95_low": rmse["ci95_low"], "RMSE_CI95_high": rmse["ci95_high"],
            "Mean_R2": r2["mean"], "Mean_fit_percent": fit["mean"],
            "Worst_pure_test": worst_name,
            "Worst_pure_test_mean_RMSE": float(test_means.max()) if len(test_means) else np.nan,
            "RMSE_variation_across_test_experiments": (
                float(test_means.std(ddof=1)) if len(test_means) > 1 else 0.0
            ),
        })
    ranking = pd.DataFrame(rows)
    ranking["RMSE_rank_within_output"] = ranking.groupby("Output")["Mean_RMSE"].rank(
        method="min", ascending=True
    ).astype(int)
    ranking["Evidence_beats_all_baselines"] = False
    for output in ranking["Output"].unique():
        evidence = paired[
            (paired["Evaluation"] == "ALL_PURE_TESTS_POOLED")
            & (paired["Output"] == output) & (paired["Metric"] == "RMSE")
        ]
        supported = len(evidence) == 2 and bool(evidence["Clear_hybrid_improvement"].all())
        ranking.loc[
            (ranking["Output"] == output) & (ranking["Method"] == "hybrid_lstm"),
            "Evidence_beats_all_baselines",
        ] = supported
    return ranking.sort_values(["Output", "RMSE_rank_within_output", "Method"])


def strict_validation_metrics(bundle, data, validation_pairs, startup_gain, device):
    measured_parts, predicted_parts = [], []
    for record_index in sorted(set(validation_pairs[:, 0].tolist())):
        subset = validation_pairs[validation_pairs[:, 0] == record_index]
        record = data["records"][record_index]
        targets = subset[:, 1]
        measured, predictions = predictions_for_record(bundle, record, targets, startup_gain, device)
        measured_parts.append(measured[:, 0])
        predicted_parts.append(predictions["hybrid_lstm"][:, 0])
    measured = np.concatenate(measured_parts)
    predicted = np.concatenate(predicted_parts)
    return calculate_metrics(
        measured, predicted, negligible_range=NEGLIGIBLE_SIGNAL_RANGE["Displacement"]
    )


def run_ablation(arguments, settings, data, training_pairs, validation_pairs, startup_gain, device):
    root = settings["root"] / "FeatureAblation"
    results = root / "Results"
    figures = root / "Figures"
    results.mkdir(parents=True, exist_ok=True)
    figures.mkdir(parents=True, exist_ok=True)
    full_indices = tuple(range(len(ONE_STEP_FEATURE_NAMES)))
    print("\nFEATURE ABLATION: validation-only backward elimination")
    full_bundle = train_predictor(
        data["records"], training_pairs, validation_pairs, full_indices,
        arguments.ablation_seed, device, settings["epochs"], settings["samples"],
        settings["patience"],
    )
    full_metric = strict_validation_metrics(full_bundle, data, validation_pairs, startup_gain, device)
    current_indices = full_indices
    current_bundle = full_bundle
    current_metric = full_metric
    rows = []
    selected_features = []

    for step in range(1, settings["max_removals"] + 1):
        candidates = list(current_indices)
        if settings["candidate_limit"] is not None:
            candidates = candidates[:settings["candidate_limit"]]
        best = None
        candidate_row_indices = []
        for removed in candidates:
            retained = tuple(index for index in current_indices if index != removed)
            print(f"\nAblation step {step}: testing removal of {ONE_STEP_FEATURE_NAMES[removed]}")
            bundle = train_predictor(
                data["records"], training_pairs, validation_pairs, retained,
                arguments.ablation_seed, device, settings["epochs"], settings["samples"],
                settings["patience"], verbose=False,
            )
            metric = strict_validation_metrics(bundle, data, validation_pairs, startup_gain, device)
            rmse_full_change = 100.0 * (metric["RMSE"] - full_metric["RMSE"]) / full_metric["RMSE"]
            fit_full_drop = full_metric["Fit_percent"] - metric["Fit_percent"]
            rmse_current_change = 100.0 * (metric["RMSE"] - current_metric["RMSE"]) / current_metric["RMSE"]
            fit_current_drop = current_metric["Fit_percent"] - metric["Fit_percent"]
            accepted = bool(
                rmse_full_change <= arguments.validation_rmse_increase
                and fit_full_drop <= arguments.validation_fit_drop
            )
            rows.append({
                "Step": step,
                "Candidate_removed": ONE_STEP_FEATURE_NAMES[removed],
                "Candidate_index_1_based": removed + 1,
                "Retained_feature_count": len(retained),
                "Retained_features": "; ".join(ONE_STEP_FEATURE_NAMES[i] for i in retained),
                "Validation_RMSE": metric["RMSE"],
                "Validation_fit_percent": metric["Fit_percent"],
                "RMSE_change_from_full_percent": rmse_full_change,
                "Fit_drop_from_full_points": fit_full_drop,
                "RMSE_change_from_current_percent": rmse_current_change,
                "Fit_drop_from_current_points": fit_current_drop,
                "Within_validation_limits": accepted,
                "Selected_this_step": False,
            })
            row_index = len(rows) - 1
            candidate_row_indices.append(row_index)
            if accepted and (best is None or metric["RMSE"] < best["metric"]["RMSE"]):
                best = {"removed": removed, "indices": retained, "bundle": bundle,
                        "metric": metric, "row_index": row_index}
        if best is None:
            break
        rows[best["row_index"]]["Selected_this_step"] = True
        selected_features.append(ONE_STEP_FEATURE_NAMES[best["removed"]])
        current_indices = best["indices"]
        current_bundle = best["bundle"]
        current_metric = best["metric"]
        print(f"Selected removal: {ONE_STEP_FEATURE_NAMES[best['removed']]}")

    table = pd.DataFrame(rows)
    table.to_csv(results / "feature_ablation_table.csv", index=False)
    selected_text = [
        f"Evaluation label: {settings['label']}",
        "Selection data: strict development validation windows only",
        f"Seed used for selection: {arguments.ablation_seed}",
        f"Removed feature count: {len(selected_features)}",
        "Removed features: " + (", ".join(selected_features) if selected_features else "none"),
        "Retained features: " + ", ".join(ONE_STEP_FEATURE_NAMES[i] for i in current_indices),
        f"Full validation RMSE: {full_metric['RMSE']:.9g} mm",
        f"Selected validation RMSE: {current_metric['RMSE']:.9g} mm",
        f"Full validation fit: {full_metric['Fit_percent']:.6f}%",
        f"Selected validation fit: {current_metric['Fit_percent']:.6f}%",
    ]

    # Pure-test predictions are evaluated only after selection is frozen.
    pure_metrics, worst = evaluate_pure_tests(current_bundle, data, startup_gain, device)
    final_pure = pure_metrics[pure_metrics["Method"] == "hybrid_lstm"].copy()
    final_pure.to_csv(results / "final_reduced_pure_test_metrics.csv", index=False)
    displacement = final_pure[
        (final_pure["Output"] == "Displacement")
        & (final_pure["Evaluation"] != "ALL_PURE_TESTS_POOLED")
    ]
    passed = bool(
        displacement["Fit_percent"].notna().all()
        and (displacement["Fit_percent"] >= arguments.pure_test_minimum_fit).all()
    )
    selected_text.append(
        f"Pure-test confirmation passed (all displacement fits >= "
        f"{arguments.pure_test_minimum_fit:g}%): {passed}"
    )
    (results / "selected_features.txt").write_text("\n".join(selected_text) + "\n", encoding="utf-8")

    if not table.empty:
        labels = [f"S{row.Step}: -{row.Candidate_removed}" for row in table.itertuples()]
        colors = ["#009E73" if value else "#9e9e9e" for value in table["Selected_this_step"]]
        figure, axes = plt.subplots(2, 1, figsize=(max(10, 0.38 * len(table)), 8), sharex=True)
        axes[0].bar(range(len(table)), table["RMSE_change_from_full_percent"], color=colors)
        axes[0].axhline(arguments.validation_rmse_increase, color="black", ls="--")
        axes[0].set_ylabel("Validation RMSE change from full (%)")
        axes[1].bar(range(len(table)), table["Fit_drop_from_full_points"], color=colors)
        axes[1].axhline(arguments.validation_fit_drop, color="black", ls="--")
        axes[1].set_ylabel("Validation fit drop from full (points)")
        axes[1].set_xticks(range(len(table)), labels, rotation=75, ha="right", fontsize=8)
        for axis in axes:
            axis.grid(True, axis="y", alpha=0.3)
        figure.suptitle("Validation-only backward feature elimination (green = selected)")
        figure.tight_layout()
        figure.savefig(figures / "feature_ablation_results.png", dpi=220)
        plt.close(figure)
    return {
        "removed": selected_features, "retained": [ONE_STEP_FEATURE_NAMES[i] for i in current_indices],
        "passed": passed, "full_metric": full_metric, "selected_metric": current_metric,
        "worst": worst,
    }


def acf(values, maximum_lag=50):
    values = np.asarray(values, dtype=float) - np.mean(values)
    denominator = float(np.dot(values, values))
    if denominator <= 0:
        return np.zeros(maximum_lag + 1)
    return np.asarray([
        float(np.dot(values[:len(values) - lag], values[lag:]) / denominator)
        for lag in range(maximum_lag + 1)
    ])


def plot_worst_case(worst, figure_folder):
    if worst is None:
        return
    time, measured, predicted = worst["time"], worst["measured"], worst["predicted"]
    figure, axes = plt.subplots(2, 2, figsize=(12, 7), sharex="col")
    for column, output, unit, color in (
        (0, "Displacement", "mm", "#CC79A7"), (1, "Lorentz force (causal rule)", "N", "#0072B2")
    ):
        axes[0, column].plot(time, measured[:, column], color="black", lw=1.8, label="measured")
        axes[0, column].plot(time, predicted[:, column], color=color, ls="--", lw=1.3, label="predicted")
        axes[0, column].set_title(output)
        axes[0, column].set_ylabel(unit)
        axes[0, column].legend(frameon=False)
        error = measured[:, column] - predicted[:, column]
        axes[1, column].plot(time, error, color="#D55E00", lw=0.9)
        axes[1, column].axhline(0, color="black", lw=0.7)
        axes[1, column].set_ylabel(f"error ({unit})")
        axes[1, column].set_xlabel("time (s)")
        for row in (0, 1):
            axes[row, column].grid(True, alpha=0.3)
    figure.suptitle(
        f"Worst pure-test displacement fit across seeds: {worst['name']}, seed {worst['seed']}"
    )
    figure.tight_layout()
    figure.savefig(figure_folder / "worst_case_pure_test.png", dpi=220)
    plt.close(figure)

    figure, axes = plt.subplots(2, 2, figsize=(12, 7))
    for row, output, unit in ((0, "Displacement", "mm"), (1, "Lorentz force", "N")):
        error = measured[:, row] - predicted[:, row]
        axes[row, 0].plot(time, error, color="#D55E00", lw=0.9)
        axes[row, 0].axhline(0, color="black", lw=0.7)
        axes[row, 0].set_ylabel(f"{output} error ({unit})")
        axes[row, 0].set_xlabel("time (s)")
        correlation = acf(error)
        axes[row, 1].stem(range(len(correlation)), correlation, basefmt=" ")
        axes[row, 1].axhline(0.2, color="black", ls="--", lw=0.8)
        axes[row, 1].axhline(-0.2, color="black", ls="--", lw=0.8)
        axes[row, 1].set_ylabel("residual autocorrelation")
        axes[row, 1].set_xlabel("lag (samples)")
        for column in (0, 1):
            axes[row, column].grid(True, alpha=0.3)
    figure.suptitle("Worst-case residual diagnostics")
    figure.tight_layout()
    figure.savefig(figure_folder / "residual_diagnostics.png", dpi=220)
    plt.close(figure)


