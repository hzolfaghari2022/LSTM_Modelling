def run_autonomous(settings):
    autonomous_root = settings["root"] / "Autonomous"
    environment = os.environ.copy()
    environment["DLSTM_SKIP_GITHUB_PUSH"] = "1"
    environment["DLSTM_AUTONOMOUS_RESULTS_FOLDER"] = str(autonomous_root / "Results")
    environment["DLSTM_AUTONOMOUS_FIGURES_FOLDER"] = str(autonomous_root / "Figures")
    if settings["label"] != "REPORTABLE":
        environment["DLSTM_EPOCHS"] = "1"
        environment["DLSTM_SAMPLES_PER_EPOCH"] = "512"
