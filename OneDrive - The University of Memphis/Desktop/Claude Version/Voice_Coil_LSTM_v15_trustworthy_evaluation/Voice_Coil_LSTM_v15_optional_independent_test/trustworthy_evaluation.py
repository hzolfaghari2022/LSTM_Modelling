def main() -> None:
    arguments = parse_arguments()
    settings = configure(arguments)
    torch.set_num_threads(CPU_THREADS)
    device = torch.device("cuda:0" if torch.cuda.is_available() else "cpu")
    if device.type == "cuda":
        print(f"Evaluation device: {device}, {torch.cuda.get_device_name(0)}")
    else:
        print("Evaluation device: cpu")
    print(f"Evaluation status: {settings['label']}")
    print(f"Output root: {settings['root']}")
    settings["root"].mkdir(parents=True, exist_ok=True)

    print("\nLoading and auditing the measured records ...", flush=True)
    data = prepare_data(HERE)
    records = data["records"]
    ensure_one_step_arrays(records, include_pure=False)
    training_pairs = strict_role_pairs(records, "training")
    validation_pairs = strict_role_pairs(records, "validation")
    internal_test_pairs = strict_role_pairs(records, "test")
    integrity = verify_integrity(
        data, training_pairs, validation_pairs, internal_test_pairs,
        settings["root"] / "DataIntegrity",
    )
    print(f"Data-integrity checks passed: {len(integrity)}/{len(integrity)}")
    print(f"Strict training windows: {len(training_pairs):,}")
    print(f"Strict validation windows: {len(validation_pairs):,}")
    print(f"Strict internal-test windows: {len(internal_test_pairs):,}")
    startup_gain = _fit_startup_force_gain(records)

    ablation = None
    repeatability = None
    if arguments.mode in ("ablation", "all"):
        ablation = run_ablation(
            arguments, settings, data, training_pairs, validation_pairs,
            startup_gain, device,
        )
    if arguments.mode in ("baseline", "repeatability", "all"):
        repeatability = run_repeatability(
            arguments, settings, data, training_pairs, validation_pairs,
            startup_gain, device,
        )
    autonomous_ran = False
    if arguments.run_autonomous:
        print("\nRunning the separate autonomous/free-running evaluation ...")
        run_autonomous(settings)
        autonomous_ran = True
    write_report(arguments, settings, integrity, repeatability, ablation, autonomous_ran)

    if os.environ.get("DLSTM_SKIP_GITHUB_PUSH", "0") != "1":
        run_time = datetime.now().astimezone()
        (settings["root"] / "last_github_update.txt").write_text(
            f"Latest completed trustworthy evaluation: {run_time.isoformat()}\n",
            encoding="utf-8",
        )
        try:
            push_simulation(
                HERE,
                commit_message="Update trustworthy V15 evaluation - "
                f"{run_time.strftime('%Y-%m-%d %H:%M:%S %Z')}",
            )
        except GitPushError as error:
            print("\nEvaluation finished, but GitHub push failed:")
            print(error)
            raise SystemExit(1) from error
    else:
        print("GitHub push skipped because DLSTM_SKIP_GITHUB_PUSH=1.")
    print("\nTrustworthy evaluation completed:", settings["root"])


if __name__ == "__main__":
    main()
